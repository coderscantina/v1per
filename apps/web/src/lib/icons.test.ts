import { readdirSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

import lucideSet from '@iconify-json/lucide/icons.json'
import { expect, test } from 'vitest'

/**
 * The admin app ships only the Lucide icons its sources name. This test writes that subset to
 * `icons.ts` as a file snapshot: after adding or dropping an icon, run
 * `bunx vitest run -u src/lib/icons.test.ts`. A name Lucide does not have fails here.
 */
const src = fileURLToPath(new URL('..', import.meta.url))
const generated = 'lib/icons.ts'

function usedNames(): string[] {
  const names = new Set<string>()
  for (const file of readdirSync(src, { recursive: true, encoding: 'utf8' })) {
    if (!/\.(ts|vue)$/.test(file) || file === generated) continue
    for (const match of readFileSync(join(src, file), 'utf8').matchAll(/lucide:([a-z0-9]+(?:-[a-z0-9]+)*)/g)) {
      if (match[1]) names.add(match[1])
    }
  }
  return [...names].sort()
}

function body(name: string): string {
  const icons: Record<string, { body: string } | undefined> = lucideSet.icons
  const aliases: Record<string, { parent: string } | undefined> = lucideSet.aliases
  const icon = icons[name] ?? icons[aliases[name]?.parent ?? '']
  if (!icon) throw new Error(`Lucide has no icon "${name}"`)
  return icon.body
}

test('the icon subset holds exactly the Lucide icons the sources use', async () => {
  const entries = usedNames().map((name) => `    '${name}': { body: ${JSON.stringify(body(name))} },`)
  const source = [
    '// Generated by icons.test.ts from the `lucide:` names under src. Do not edit by hand: use an',
    '// icon, then run `bunx vitest run -u src/lib/icons.test.ts`. ISC licensed path data from',
    '// `@iconify-json/lucide`.',
    '',
    'export const lucide = {',
    "  prefix: 'lucide',",
    `  width: ${lucideSet.width},`,
    `  height: ${lucideSet.height},`,
    '  icons: {',
    ...entries,
    '  },',
    '} as const',
    '',
    'export type IconName = `lucide:${keyof typeof lucide.icons}`',
    '',
  ].join('\n')

  await expect(source).toMatchFileSnapshot('./icons.ts')
})
